import assert from 'node:assert/strict';
import { assetVersions, versionGraph, retentionEntry } from '../src/library/lifecycle.ts';
import { newStudioMetadata } from '../src/library/provenance.ts';
const root = newStudioMetadata('general_generation'), up = newStudioMetadata('upscale_result',root), bg = newStudioMetadata('background_removed',up), branch = newStudioMetadata('inpaint_variant',root);
const output=(tag,id)=>({id,metadata:JSON.stringify({sui_extra_data:tag}),request:{},swarmSourcePath:`day/${id}.png`});
const a=output(root,'source'),b=output(up,'up'),c=output(bg,'bg'),d=output(branch,'branch');
assert.equal(assetVersions(c,[a,b,c,d]).length,4,'sibling variants remain visible');
assert.equal(assetVersions(c,[c]).filter(x=>!x.output).length,1,'missing parent is explicit');
assert.ok(assetVersions(c,[a,b,c,{...b,id:'alias'}]).find(x=>x.assetId===up.studio_asset_id).ambiguous);
assert.equal(retentionEntry(a,b,'scope',true).sourceAssetId,root.studio_asset_id);
assert.equal(retentionEntry(a,b,'scope',false),null,'failed decode cannot queue source');
assert.equal(retentionEntry(a,b,'',true),null,'unknown scope cannot queue source');
assert.equal(retentionEntry(a,c,'scope',true),null,'only actual immediate parents may be superseded');
assert.equal(retentionEntry(a,{...b,swarmSourcePath:a.swarmSourcePath},'scope',true),null);
assert.equal(retentionEntry({...a,swarmSourcePath:'../outside'},b,'scope',true),null);
assert.equal(assetVersions({...a,metadata:'{}'},[a,b]).length,0,'no prompt-based inference');
console.log('Version branches/missing/duplicate parents and verified replacement queue safety: PASS');

const siblingTag=newStudioMetadata('upscale_result',root),sibling=output(siblingTag,'sibling-upscale');
const graph=versionGraph(assetVersions(c,[a,b,c,sibling]));
assert.equal(graph.edges.length,3);
const positions=new Map(graph.nodes.map(point=>[point.node.output?.id,point]));
assert.equal(positions.get('up').y,positions.get('sibling-upscale').y);
assert.notEqual(positions.get('up').x,positions.get('sibling-upscale').x);
assert.equal(positions.get('bg').x,positions.get('up').x,'background removal stays in its actual upscale lane');
assert.equal(positions.get('bg').children,0);assert.equal(positions.get('sibling-upscale').children,0);
assert.equal(positions.get('source').x,(positions.get('up').x+positions.get('sibling-upscale').x)/2);
const ambiguousGraph=versionGraph(assetVersions(c,[a,b,c,{...b,id:'duplicate'}]));
assert.ok(!ambiguousGraph.edges.some(edge=>edge.parent===up.studio_asset_id||edge.child===up.studio_asset_id));
const missingGraph=versionGraph(assetVersions(c,[c]));assert.equal(missingGraph.edges.length,1);assert.ok(!missingGraph.edges[0].from.node.output);
const cyclic=versionGraph([{assetId:'a',parentId:'b',stage:'draft',ambiguous:false},{assetId:'b',parentId:'a',stage:'upscale',ambiguous:false}]);
assert.equal(cyclic.edges.length,0);assert.equal(cyclic.nodes.length,2);assert.ok(cyclic.nodes.every(node=>node.unresolved));
assert.equal(versionGraph([]).nodes.length,0);
console.log('Version graph sibling lanes, exact edges, two branch ends, missing placeholders, ambiguity and cycle quarantine: PASS');

const lumiRoot=output({...root,studio_origin:'lumiswarm'},'lumi-draft');
const lumiUp=output({...up,studio_origin:'lumiswarm'},'lumi-up');
const lumiBg=output({...bg,studio_origin:'lumiswarm'},'lumi-bg');
const standaloneBranch=output({...siblingTag,studio_origin:'standalone'},'standalone-up');
const mixed=[lumiRoot,lumiUp,lumiBg,standaloneBranch];
for(const current of mixed){const family=assetVersions(current,mixed);assert.equal(family.length,4);assert.ok(family.every(n=>n.output),'cross-Studio parents are indexed, never missing');assert.equal(versionGraph(family).edges.length,3);}
const conflictingBranch=output({...siblingTag,studio_pipeline_id:newStudioMetadata().studio_pipeline_id},'conflicting-up');
const reconciled=assetVersions(conflictingBranch,[lumiRoot,lumiUp,lumiBg,conflictingBranch]);
assert.equal(reconciled.length,4);assert.equal(reconciled.find(n=>n.output?.id==='conflicting-up').pipelineConflict,true);assert.ok(reconciled.every(n=>n.output));
assert.equal(versionGraph(reconciled).edges.length,3,'exact parent link is visible despite pipeline disagreement');
const duplicateAcrossOrigins=assetVersions(standaloneBranch,[...mixed,output({...root,studio_origin:'standalone'},'duplicate-root')]);
assert.equal(duplicateAcrossOrigins.find(n=>n.assetId===root.studio_asset_id).ambiguous,true);
assert.ok(!versionGraph(duplicateAcrossOrigins).edges.some(e=>e.parent===root.studio_asset_id));
const differentFullId=root.studio_asset_id.slice(0,-1)+(root.studio_asset_id.endsWith('0')?'1':'0');
const prefixOnly=assetVersions(output({...siblingTag,studio_parent_id:differentFullId},'prefix-child'),[lumiRoot]);
assert.ok(prefixOnly.some(n=>n.assetId===differentFullId&&!n.output),'matching shortened ID prefixes never invent a parent');
console.log('Cross-Studio reconciliation from every node, pipeline-conflict warnings, global duplicate detection and exact full-ID matching: PASS');
