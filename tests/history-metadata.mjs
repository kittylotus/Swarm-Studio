import assert from 'node:assert/strict';
import { durationSeconds, generationTiming, historyCreatedAt, compareOutputDates } from '../src/swarm/history-metadata.ts';
import { modelFolderPaths, modelInFolder, folderDepth } from '../src/models/folders.ts';

assert.equal(durationSeconds('3.70 min'), 222);
assert.equal(durationSeconds('2.5 milliseconds'), .0025);
assert.equal(durationSeconds('1.5 hours'), 5400);
for (const input of [-1, NaN, 'unknown', '-3 sec', '123cats']) assert.equal(durationSeconds(input), undefined);
assert.equal(durationSeconds(3.7), 3.7);
assert.equal(durationSeconds('9'.repeat(400)+' min'), undefined);
const circular={generation_time:'3.70 min'};circular.self=circular;
assert.equal(generationTiming(circular).generationTimeMs,222000);
assert.deepEqual(generationTiming(JSON.stringify({sui_extra_data:{prep_time:'4.25 sec',generation_time:'3.70 min'}})), {prepTimeMs:4250,generationTimeMs:222000,totalTimeMs:226250});
assert.deepEqual(generationTiming({sui_extra_data:JSON.stringify({prep_time:'500 ms',generation_time:2,total_time:'2.5 sec'})}), {prepTimeMs:500,generationTimeMs:2000,totalTimeMs:2500});
assert.deepEqual(generationTiming('2 sec (prep) and 3.70 min (gen)'), {prepTimeMs:2000,generationTimeMs:222000,totalTimeMs:224000});
assert.deepEqual(generationTiming('2 (prep) and 3 (gen) seconds'), {prepTimeMs:2000,generationTimeMs:3000,totalTimeMs:5000});
assert.equal(generationTiming('Generation time: 3.70 min').generationTimeMs, 222000);
assert.equal(generationTiming({prompt:'three minutes'}).generationTimeMs, undefined);

const local = (hour, minute=0, second=0) => new Date(2026,10,9,hour,minute,second).getTime();
assert.equal(historyCreatedAt('2026-11-09/1456-prompt-model-seed.png', ''), local(14,56));
assert.equal(historyCreatedAt('2026-11-09/14-56-21-prompt.png', ''), local(14,56,21));
assert.equal(historyCreatedAt('2026-11-09/145621-prompt.png', ''), local(14,56,21));
assert.equal(historyCreatedAt('2026-11-09/1456-prompt.png', '', local(12)), local(14,56), 'repair old cached noon');
assert.equal(historyCreatedAt('2026-11-09/1456-prompt.png', '', local(14,56,43)+123), local(14,56,43)+123, 'keep a precise live capture');
const metadata = JSON.stringify({sui_extra_data:{date:'2026-11-09T18:02:34Z'}});
assert.equal(historyCreatedAt('2026-11-09/1456-prompt.png', metadata), Date.parse('2026-11-09T18:02:34Z'));
assert.equal(historyCreatedAt('custom.png', {sui_extra_data:{date:'2026-11-09',time:'15:12:13'}}), local(15,12,13));
assert.equal(historyCreatedAt('2026-11-09/custom.png', ''), local(0), 'date-only fallback uses a stable local date');
assert.equal(historyCreatedAt('unknown.png', ''), 0, 'undated images do not jump to the sync time');
assert.equal(historyCreatedAt('2026-02-30/custom.png', ''), 0, 'invalid dates do not roll into another month');
assert.equal(historyCreatedAt('2026-11-09/9966-invalid.png', ''), local(0));
const records = ['a','c','b'].map(id => ({id,createdAt:local(0),swarmSourcePath:`2026-11-09/${id}.png`}));
const ordered = records.toSorted(compareOutputDates).map(item=>item.id);
assert.deepEqual(ordered, ['c','b','a']);
assert.deepEqual(records.toReversed().sort(compareOutputDates).map(item=>item.id), ordered);

const models=[{name:'root.safetensors'},{name:'anime\\base.safetensors'},{name:'anime/nested/other.safetensors'},{name:'anime2/model.safetensors'}];
assert.deepEqual(modelFolderPaths(models), ['anime','anime/nested','anime2']);
assert.deepEqual(models.filter(model=>modelInFolder(model.name,'',0)).map(model=>model.name), ['root.safetensors']);
assert.equal(models.filter(model=>modelInFolder(model.name,'',1)).length, 3);
assert.equal(models.filter(model=>modelInFolder(model.name,'anime',0)).length, 1);
assert.equal(models.filter(model=>modelInFolder(model.name,'anime',1)).length, 2);
assert.equal(modelInFolder('anime2/model.safetensors','anime',20), false);
assert.equal(folderDepth(null,20),20);
assert.equal(folderDepth('',20),20);
assert.equal(folderDepth(-1),0);
assert.equal(folderDepth(200),20);
assert.equal(folderDepth('2.9'),2);
console.log('history timing/date and model folder regressions: ok');
