import assert from 'node:assert/strict';
import { vacuumViewRows, defaultVacuumView, isLumiSwarmOutput, LUMI_LIBRARY_VIEW } from '../src/library/views.ts';
import { newStudioMetadata } from '../src/library/provenance.ts';
import { normalizeLibraryFolderSelection } from '../src/library/session.ts';
const tag = newStudioMetadata('expression_draft'); tag.studio_origin = 'lumiswarm'; tag.studio_created_at = String(new Date(2026, 10, 23, 18, 20).getTime());
const raw = JSON.stringify({ sui_extra_data: tag });
const rows = Array.from({length: 4000}, (_, i) => ({ path: `raw/2026-05-28/${String(i).padStart(6,'0')}-old.png`, assetId: '', stage: 'untagged', reason: 'Favorite', status: 'protected' }));
const draft = { path: 'raw/2026-11-23/1817001-draft.png', assetId: tag.studio_asset_id, stage: 'expression_draft', reason: 'Grace period', status: 'review' };
rows.push(draft);
const files = [{path:draft.path,metadata:raw}];
const view = overrides => vacuumViewRows(rows, files, {...defaultVacuumView(), ...overrides});
assert.equal(view()[0], draft, 'newest metadata-backed result precedes 4k historical outputs');
assert.notEqual(view({sort:'oldest'})[0], draft);
assert.deepEqual(view({origin:'lumiswarm'}), [draft]);
assert.equal(view({origin:'untagged'}).length, 4000);
assert.equal(view({status:'protected'}).length, 4000);
assert.deepEqual(view({search:tag.studio_asset_id}), [draft]);
assert.deepEqual(view({search:'expression draft'}), [draft]);
assert.equal(view({search:'no-such-output'}).length, 0);
const candidate = {...draft,path:'candidate.png',status:'candidate'};
assert.equal(vacuumViewRows([...rows,candidate],files,{...defaultVacuumView(),sort:'priority'})[0],candidate);
assert.equal(rows[0].stage, 'untagged', 'projection never mutates inventory order');
assert.equal(isLumiSwarmOutput({metadata:raw,swarmSourcePath:draft.path}),true);
assert.equal(isLumiSwarmOutput({metadata:raw,swarmSourcePath:'../outside.png'}),false);
assert.equal(isLumiSwarmOutput({metadata:'{}',swarmSourcePath:draft.path}),false);
assert.equal(isLumiSwarmOutput({metadata:'',swarmSourcePath:draft.path,request:{extra_metadata:tag}}),false,'request hints are not saved provenance');
assert.equal(isLumiSwarmOutput({metadata:JSON.stringify({sui_extra_data:{...tag,studio_origin:'standalone'}}),swarmSourcePath:draft.path}),false);
assert.equal(normalizeLibraryFolderSelection(LUMI_LIBRARY_VIEW,[]),LUMI_LIBRARY_VIEW,'virtual selection survives reload without a physical folder');
console.log('Library virtual Lumi collection and 4k-row Vacuum search/filter/sort projection: PASS');
