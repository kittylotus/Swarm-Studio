import assert from 'node:assert/strict';
import { defaultSheet, expressionTiles, expressionRequest, normalizeSheet, isAdapterModel, livePortraitWorkflow, ipAdapterWorkflow } from '../src/expressions/pipeline.ts';
import { zipStore } from '../src/expressions/zip.ts';
import { expressionFailure } from '../src/expressions/errors.ts';
const params=[{id:'useipadapter',values:['None','PLUS (high strength)']}];
const project={...defaultSheet(),model:'portrait.safetensors',reference:'data:image/png;base64,aGVsbG8='};
const tile=expressionTiles(1)[0];
const request=expressionRequest(project,tile,params);
assert.equal(request.promptimages,project.reference);
assert.equal(request.useipadapter,'PLUS (high strength)');
assert.equal(request.batchsize,1);
assert.equal(request.images,1);
assert.equal(request.imageformat,'PNG');
assert.equal(request.seed,project.seed);
assert.equal(request.ipadapterend,.8);
assert.equal(expressionRequest(project,{...tile,seedOffset:3},params).seed,project.seed+3);
assert.throws(()=>expressionRequest({...project,start:.9,end:.8},tile,params),/start/);
assert.throws(()=>expressionRequest({...project,reference:''},tile,params),/reference/);
assert.throws(()=>expressionRequest(project,tile,[]),/advertised/);
assert.equal(isAdapterModel({name:'Anima',architecture:'anima'}),false);
assert.equal(isAdapterModel({name:'XL',architecture:'stable-diffusion-xl-v0_9-base'}),true);
assert.equal(expressionRequest({...project,engine:'img2img'},tile,params).initimage,project.reference);
assert.equal('promptimages' in expressionRequest({...project,engine:'text'},tile,params),false);
const normalized=normalizeSheet({...project,width:99999,height:512,columns:40,weight:20});
assert.equal(normalized.width,1536);assert.equal(normalized.columns,8);assert.equal(normalized.weight,2);
assert.equal(normalizeSheet({...project,tiles:[{...tile,image:'https://untrusted.example/image.png'}]}).tiles[0].image,'');
assert.throws(()=>normalizeSheet({...project,reference:'https://untrusted.example/ref.png'}),/embedded/);
const schema={ExpressionEditor:{input:{required:{smile:['FLOAT',{default:0}],sample_parts:[['OnlyExpression','All']]}}},SwarmLoadImageB64:{},SwarmSaveImageWS:{},IPAdapterUnifiedLoader:{},IPAdapter:{},CheckpointLoaderSimple:{input:{required:{ckpt_name:[['portrait.safetensors']]}}}};
const portrait=livePortraitWorkflow(project.reference,{...tile.motion,smile:99},schema);
assert.equal(portrait['2'].inputs.smile,1.3);
assert.deepEqual(portrait['2'].inputs.src_image,['1',0]);
assert.equal(portrait['9'].class_type,'SwarmSaveImageWS');
assert.throws(()=>livePortraitWorkflow(project.reference,tile.motion,{}),/requires/);
const graph=ipAdapterWorkflow(project,tile,schema);
assert.equal(graph['1'].inputs.ckpt_name,'portrait.safetensors');
assert.equal(graph['5'].inputs.text,request.prompt);
assert.deepEqual(graph['8'].inputs.model,['4',0]);
assert.equal(graph['10'].class_type,'SwarmSaveImageWS');
assert.throws(()=>ipAdapterWorkflow({...project,useLoras:true},tile,schema),/LoRAs/);
assert.throws(()=>ipAdapterWorkflow({...project,model:'unavailable'},tile,schema),/inventory/);
const bytes=new Uint8Array(await zipStore([{name:'hello.txt',data:new TextEncoder().encode('hello')}]).arrayBuffer());
const view=new DataView(bytes.buffer);
assert.equal(view.getUint32(0,true),0x04034b50);
assert.equal(view.getUint32(14,true),0x3610a686); // Known CRC-32 of 'hello'.
assert.equal(view.getUint32(bytes.length-22,true),0x06054b50);
assert.equal(view.getUint16(bytes.length-12,true),1);
const mismatch=expressionFailure('Resampler: size mismatch for proj_in.weight [1280, 1280] / [1280, 1664]');
assert.equal(mismatch.stop,true);assert.equal(mismatch.setup,true);assert.match(mismatch.message,/actual CLIP-ViT-H/);
assert.equal(expressionFailure('CUDA out of memory').stop,true);
assert.deepEqual(expressionFailure('unrelated error'),{message:'unrelated error',stop:false,setup:false});
console.log('expression pipeline contracts: ok');
